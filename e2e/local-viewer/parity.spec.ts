import { expect, test } from '@playwright/test'

const pages = [['/#/collections', 'Colecciones'], ['/#/profiles', 'Perfiles y actividades'], ['/#/settings', 'Configuración'], ['/#/official-sources', 'Fuentes oficiales'], ['/#/library', 'Biblioteca local']] as const

test('muestra contador real, grupos operativos y conserva historial al limpiar', async ({ page }) => {
  await page.goto('/#/collections')
  await expect(page.getByText('99+', { exact: true })).toBeVisible()
  const jobs = page.getByRole('button', { name: /Abrir centro de ejecuciones: 101 sin leer/ })
  await expect(jobs).toBeVisible(); await jobs.click()
  await expect(page.getByRole('heading', { name: 'Centro de ejecuciones' })).toBeVisible()
  await expect(page.getByText('En curso', { exact: true })).toBeVisible()
  await expect(page.getByText('Requieren atención', { exact: true })).toBeVisible()
  await expect(page.getByText('Finalizadas sin leer', { exact: true })).toBeVisible()
  const beforeClear = await page.evaluate(async () => fetch('/api/v1/runs').then((response) => response.json())) as { items: Array<{ status: string; readAt: string | null }> }
  expect(beforeClear.items).toHaveLength(101)
  expect(beforeClear.items.filter((run) => run.status === 'completed' || run.status === 'failed').every((run) => run.readAt === null)).toBeTruthy()
  await page.getByRole('button', { name: 'Limpiar finalizadas' }).click()
  await page.reload()
  const afterClear = await page.evaluate(async () => fetch('/api/v1/runs').then((response) => response.json())) as { items: Array<{ status: string; readAt: string | null }> }
  expect(afterClear.items).toHaveLength(101)
  expect(afterClear.items.filter((run) => run.status === 'completed' || run.status === 'failed').every((run) => run.readAt !== null)).toBeTruthy()
  expect(afterClear.items.filter((run) => run.status === 'queued' || run.status === 'running' || run.status === 'blocked').every((run) => run.readAt === null)).toBeTruthy()
  const reduced = page.getByRole('button', { name: /Abrir centro de ejecuciones: 3 sin leer/ })
  await expect(reduced).toBeVisible(); await reduced.click()
  await expect(page.getByText('En curso', { exact: true })).toBeVisible()
  await expect(page.getByText('Requieren atención', { exact: true })).toBeVisible()
})

